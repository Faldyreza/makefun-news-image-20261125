function glyphWidth(font, ch) {
  const g = font[ch];
  return g ? g[0].length : 4;
}
function textWidth(font, str, s) {
  let w = 0;
  for (const ch of str) w += glyphWidth(font, ch) * s + s;
  return w - s;
}
function drawGlyph(font, ch, x, y, s, c) {
  const g = font[ch];
  if (!g) return;
  for (let r = 0; r < g.length; r++) {
    const row = g[r];
    for (let col = 0; col < row.length; col++) {
      if (row[col] === "#") rect(x + col * s, y + r * s, s, s, c);
    }
  }
}
function drawText(font, str, x, y, s, c, align) {
  const w = textWidth(font, str, s);
  let cx = x;
  if (align === "center") cx = x - Math.floor(w / 2);
  if (align === "right") cx = x - w;
  for (const ch of str) {
    drawGlyph(font, ch, cx, y, s, c);
    cx += glyphWidth(font, ch) * s + s;
  }
}

